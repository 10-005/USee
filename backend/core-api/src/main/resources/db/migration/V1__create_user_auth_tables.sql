CREATE TABLE user_accounts (
    user_account_seq INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_seq         INTEGER      NOT NULL REFERENCES users (user_seq),
    provider_seq     INTEGER      NOT NULL REFERENCES auth_providers (provider_seq),
    login_identifier VARCHAR(255) NOT NULL,
    password_hash    VARCHAR(255),
    is_deleted       BOOLEAN      NOT NULL DEFAULT FALSE,
    reg_dttm         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_accounts_user_seq UNIQUE (user_seq)
);

-- 같은 제공자의 같은 식별자는 활성 계정 1개만. 탈퇴 이력 행은 남기고 재가입은 새 행
CREATE UNIQUE INDEX uq_user_accounts_active_login ON user_accounts (provider_seq, login_identifier) WHERE is_deleted = FALSE;
