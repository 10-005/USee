-- images.reg_usr_seq ↔ users.profile_image_seq가 서로 참조하므로 images를 먼저 만들고 FK는 users 뒤에 건다

CREATE TABLE images (
    image_seq          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_key          VARCHAR(512) NOT NULL,
    mime_type          VARCHAR(100) NOT NULL,
    original_file_name VARCHAR(255),
    byte_size          BIGINT,
    reg_usr_seq        INTEGER,
    reg_dttm           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_images_image_key UNIQUE (image_key)
);

CREATE TABLE users (
    user_seq          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role              VARCHAR(15)  NOT NULL,
    nickname          VARCHAR(50),
    name              VARCHAR(100),
    birth_date        DATE,
    phone             VARCHAR(30),
    profile_image_seq BIGINT REFERENCES images (image_seq),
    account_status    VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    deleted_dttm      TIMESTAMPTZ,
    is_deleted        BOOLEAN      NOT NULL DEFAULT FALSE,
    reg_dttm          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm          TIMESTAMPTZ,
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'SHELTER', 'ADMIN')),
    -- USER는 개인정보 4종 필수, SHELTER·ADMIN은 NULL 허용
    CONSTRAINT ck_users_user_profile CHECK (
        role <> 'USER'
        OR (nickname IS NOT NULL AND name IS NOT NULL AND birth_date IS NOT NULL AND phone IS NOT NULL)
    )
);

-- 활성 USER끼리만 중복 금지(탈퇴 후 재사용 허용). 닉네임은 대소문자 무관
CREATE UNIQUE INDEX uq_users_active_nickname ON users (lower(nickname)) WHERE role = 'USER' AND is_deleted = FALSE;
CREATE UNIQUE INDEX uq_users_active_phone ON users (phone) WHERE role = 'USER' AND is_deleted = FALSE;

ALTER TABLE images ADD CONSTRAINT fk_images_reg_usr_seq FOREIGN KEY (reg_usr_seq) REFERENCES users (user_seq);

CREATE TABLE auth_providers (
    provider_seq  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_code VARCHAR(20) NOT NULL,
    provider_name VARCHAR(50),
    reg_dttm      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_auth_providers_provider_code UNIQUE (provider_code)
);

