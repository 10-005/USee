-- completed_application_seq 복합 FK는 adoption_applications 생성 뒤 아래에서 건다(상호 참조)
CREATE TABLE shelter_animals (
    animal_seq                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shelter_seq               INTEGER     NOT NULL,
    rescue_seq                INTEGER,
    completed_application_seq BIGINT,
    combination_seq           INTEGER     NOT NULL,
    gender                    VARCHAR(15) NOT NULL,
    age                       VARCHAR(30),
    is_neutered               BOOLEAN,
    microchip_number          VARCHAR(30),
    registration_number       VARCHAR(20),
    weight                    VARCHAR(30),
    description               TEXT,
    health_check              TEXT,
    vaccination_status        TEXT,
    notice_start_date         DATE        NOT NULL,
    notice_end_date           DATE        NOT NULL,
    protection_status         VARCHAR(20) NOT NULL DEFAULT 'PROTECTING',
    end_reason                VARCHAR(20),
    protection_ended_dttm     TIMESTAMPTZ,
    adoption_status           VARCHAR(20) NOT NULL DEFAULT 'UNAVAILABLE',
    adoption_reason           VARCHAR(200),
    adoption_memo             TEXT,
    is_deleted                BOOLEAN     NOT NULL DEFAULT FALSE,
    reg_usr_seq               INTEGER,
    reg_dttm                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_usr_seq               INTEGER,
    mod_dttm                  TIMESTAMPTZ,
    CONSTRAINT ck_shelter_gender CHECK (gender IN ('MALE', 'FEMALE', 'UNKNOWN')),
    CONSTRAINT ck_shelter_notice_range CHECK (notice_start_date <= notice_end_date),
    CONSTRAINT ck_shelter_protection_status CHECK (protection_status IN ('PROTECTING', 'RETURNED', 'ADOPTED', 'ENDED')),
    CONSTRAINT ck_shelter_adoption_status CHECK (adoption_status IN ('AVAILABLE', 'UNAVAILABLE', 'ADOPTED')),
    -- Q479: 어느 상태로든 전환 가능. DB는 조합만 강제(파생 탭 5종과 1:1)
    CONSTRAINT ck_shelter_status_pair CHECK (
        (protection_status = 'PROTECTING' AND adoption_status IN ('AVAILABLE', 'UNAVAILABLE'))
        OR (protection_status IN ('RETURNED', 'ENDED') AND adoption_status = 'UNAVAILABLE')
        OR (protection_status = 'ADOPTED' AND adoption_status = 'ADOPTED')
    ),
    -- 종료 상태 ↔ 종료 사유·일시. PROTECTING 복귀 시 둘 다 NULL
    CONSTRAINT ck_shelter_protection_end CHECK (
        (protection_status = 'PROTECTING' AND end_reason IS NULL AND protection_ended_dttm IS NULL)
        OR (protection_status = 'RETURNED' AND end_reason = 'RETURNED' AND protection_ended_dttm IS NOT NULL)
        OR (protection_status = 'ADOPTED' AND end_reason = 'ADOPTED' AND protection_ended_dttm IS NOT NULL)
        OR (protection_status = 'ENDED' AND end_reason IN ('NATURAL_DEATH', 'EUTHANIZED', 'OTHER')
            AND protection_ended_dttm IS NOT NULL)
    ),
    CONSTRAINT fk_shelter_animal_shelter FOREIGN KEY (shelter_seq) REFERENCES shelters (shelter_seq),
    CONSTRAINT fk_shelter_animal_rescue FOREIGN KEY (rescue_seq) REFERENCES rescue_records (rescue_seq),
    CONSTRAINT fk_shelter_animal_combination FOREIGN KEY (combination_seq) REFERENCES animal_combinations (combination_seq),
    CONSTRAINT fk_shelter_animal_reg_usr FOREIGN KEY (reg_usr_seq) REFERENCES users (user_seq),
    CONSTRAINT fk_shelter_animal_mod_usr FOREIGN KEY (mod_usr_seq) REFERENCES users (user_seq)
);
CREATE INDEX ix_shelter_animal_shelter ON shelter_animals (shelter_seq, reg_dttm) WHERE is_deleted = FALSE;
CREATE INDEX ix_shelter_animal_rescue ON shelter_animals (rescue_seq) WHERE rescue_seq IS NOT NULL;

