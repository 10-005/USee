CREATE TABLE notifications (
    notification_seq   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_seq INTEGER     NOT NULL,
    notification_type  VARCHAR(40) NOT NULL,
    message            TEXT        NOT NULL,
    target_type        VARCHAR(40),
    target_seq         BIGINT,
    missing_report_seq INTEGER,
    comment_seq        BIGINT,
    parent_comment_seq BIGINT,
    is_read            BOOLEAN     NOT NULL DEFAULT FALSE,
    read_dttm          TIMESTAMPTZ,
    is_deleted         BOOLEAN     NOT NULL DEFAULT FALSE,
    reg_dttm           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_notification_type CHECK (notification_type IN (
        'COMMENT', 'COMMENT_REPLY', 'AI_MATCH',
        'ADOPTION_SUBMITTED', 'ADOPTION_APPROVED', 'ADOPTION_REJECTED', 'ADOPTION_COMPLETED',
        'SHELTER', 'SYSTEM'
    )),
    CONSTRAINT ck_notification_target_type CHECK (target_type IS NULL OR target_type IN (
        'USER', 'MISSING', 'FOUND', 'SHELTER_ANIMAL', 'ADOPTION', 'MISSING_COMMENT', 'FOUND_COMMENT'
    )),
    -- Q446: COMMENT 계열만 댓글 참조. target은 게시물, 답글이면 루트 댓글 포함
    CONSTRAINT ck_notification_comment_ref CHECK (
        (notification_type IN ('COMMENT', 'COMMENT_REPLY')
            AND comment_seq IS NOT NULL
            AND target_type IN ('MISSING', 'FOUND') AND target_seq IS NOT NULL
            AND ((notification_type = 'COMMENT' AND parent_comment_seq IS NULL)
                OR (notification_type = 'COMMENT_REPLY' AND parent_comment_seq IS NOT NULL)))
        OR (notification_type NOT IN ('COMMENT', 'COMMENT_REPLY') AND comment_seq IS NULL AND parent_comment_seq IS NULL)
    ),
    CONSTRAINT fk_notification_recipient FOREIGN KEY (recipient_user_seq) REFERENCES users (user_seq),
    CONSTRAINT fk_notification_missing FOREIGN KEY (missing_report_seq) REFERENCES missing_reports (missing_report_seq)
);
