CREATE TABLE chat_rooms (
    chat_room_seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_type     VARCHAR(15) NOT NULL,
    user_a_seq    INTEGER     NOT NULL,
    user_b_seq    INTEGER,
    shelter_seq   INTEGER,
    reg_dttm      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- USER형은 user_a < user_b 정렬 저장, SHELTER형은 보호소만
    CONSTRAINT ck_chat_room_pair CHECK (
        (room_type = 'USER' AND user_b_seq IS NOT NULL AND shelter_seq IS NULL AND user_a_seq < user_b_seq)
        OR (room_type = 'SHELTER' AND user_b_seq IS NULL AND shelter_seq IS NOT NULL)
    ),
