CREATE TABLE rescue_records (
    rescue_seq            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shelter_seq           INTEGER      NOT NULL,
    found_report_seq      INTEGER,
    status                VARCHAR(20)  NOT NULL DEFAULT 'PROCESSING',
    completed_dttm        TIMESTAMPTZ,
    rescued_dttm          TIMESTAMPTZ  NOT NULL,
    rescue_reason_code    VARCHAR(30)  NOT NULL,
    rescue_address        VARCHAR(255) NOT NULL,
    rescue_address_detail VARCHAR(200),
    rescue_memo           TEXT,
    result_reason         TEXT,
    is_deleted            BOOLEAN      NOT NULL DEFAULT FALSE,
    reg_usr_seq           INTEGER,
    reg_dttm              TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_usr_seq           INTEGER,
    mod_dttm              TIMESTAMPTZ,
    CONSTRAINT ck_rescue_status CHECK (status IN ('PROCESSING', 'DONE', 'FAILED', 'CANCELED')),
    -- Q384: 종료 3종은 완료 시각 필수
    CONSTRAINT ck_rescue_completion_time CHECK (
        (status = 'PROCESSING' AND completed_dttm IS NULL)
        OR (status IN ('DONE', 'FAILED', 'CANCELED') AND completed_dttm IS NOT NULL)
    ),
    -- Q461: 사유 코드·장소·구조 일시는 접수 시부터 필수
    CONSTRAINT ck_rescue_reason_code CHECK (rescue_reason_code IN ('WANDERING', 'INJURY_ILLNESS', 'DANGEROUS_PLACE', 'OTHER')),
    CONSTRAINT ck_rescue_address_not_blank CHECK (length(btrim(rescue_address)) > 0),
    -- Q360: 실패·취소는 사유 필수
    CONSTRAINT ck_rescue_result_reason CHECK (
        status NOT IN ('FAILED', 'CANCELED') OR (result_reason IS NOT NULL AND length(btrim(result_reason)) > 0)
    ),
    CONSTRAINT fk_rescue_shelter FOREIGN KEY (shelter_seq) REFERENCES shelters (shelter_seq),
    CONSTRAINT fk_rescue_found FOREIGN KEY (found_report_seq) REFERENCES found_reports (found_report_seq),
    CONSTRAINT fk_rescue_reg_usr FOREIGN KEY (reg_usr_seq) REFERENCES users (user_seq),
    CONSTRAINT fk_rescue_mod_usr FOREIGN KEY (mod_usr_seq) REFERENCES users (user_seq)
);
-- Q294: 발견 신고당 비삭제 PROCESSING/DONE 합계 1건
CREATE UNIQUE INDEX uq_rescue_found_active_done ON rescue_records (found_report_seq)
    WHERE found_report_seq IS NOT NULL AND is_deleted = FALSE AND status IN ('PROCESSING', 'DONE');
-- Q464: 8.8 구조 상태 파생(신고별 최신 비삭제 구조)
CREATE INDEX ix_rescue_found_latest ON rescue_records (found_report_seq, reg_dttm DESC)
    WHERE found_report_seq IS NOT NULL AND is_deleted = FALSE;
CREATE INDEX ix_rescue_shelter ON rescue_records (shelter_seq, rescued_dttm) WHERE is_deleted = FALSE;

