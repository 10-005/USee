CREATE INDEX ix_notification_recipient ON notifications (recipient_user_seq, reg_dttm DESC) WHERE is_deleted = FALSE;
CREATE INDEX ix_notification_ai_match ON notifications (missing_report_seq, target_type, target_seq)
    WHERE notification_type = 'AI_MATCH';
