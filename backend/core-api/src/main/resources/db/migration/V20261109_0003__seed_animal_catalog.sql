-- 11. 유효 조합 = 종별 허용 색상 × 그 종의 전 품종. 개는 개 털색, 고양이는 고양이 털색, 기타 축종은 전 색상
INSERT INTO animal_combinations (breed_seq, color_seq)
SELECT b.breed_seq, c.color_seq
FROM animal_breeds b
JOIN animal_species s ON s.species_seq = b.species_seq
JOIN animal_colors c ON s.species_code = 'ETC'
    OR (s.species_code = 'DOG' AND c.color_name IN
        ('흰색', '검은색', '갈색', '회색', '크림색', '황색', '적갈색', '블랙탄', '흰색·검은색', '흰색·갈색', '삼색', '얼룩', '기타'))
