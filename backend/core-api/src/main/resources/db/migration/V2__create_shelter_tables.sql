-- DB 명세 v18 04·05와 Q406 districts. core 스키마(접속 currentSchema=core)

CREATE TABLE districts (
    district_code VARCHAR(5)  PRIMARY KEY,
    sido_name     VARCHAR(50) NOT NULL,
    sigungu_name  VARCHAR(50) NOT NULL,
    reg_dttm      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE shelters (
    shelter_seq           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shelter_name          VARCHAR(150)     NOT NULL,
    external_shelter_code VARCHAR(100),
    address               VARCHAR(255)     NOT NULL,
    latitude              DOUBLE PRECISION NOT NULL,
    longitude             DOUBLE PRECISION NOT NULL,
    phone                 VARCHAR(30)      NOT NULL,
    description           TEXT,
    operating_hours       TEXT,
    closed_days           TEXT,
    district_code         VARCHAR(5),
    profile_image_seq     BIGINT,
    background_image_seq  BIGINT,
    is_deleted            BOOLEAN          NOT NULL DEFAULT FALSE,
    reg_usr_seq           INTEGER,
    reg_dttm              TIMESTAMPTZ      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_usr_seq           INTEGER,
    mod_dttm              TIMESTAMPTZ,
    CONSTRAINT uq_shelters_external_shelter_code UNIQUE (external_shelter_code),
    CONSTRAINT ck_shelters_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_shelters_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT fk_shelters_district_code FOREIGN KEY (district_code) REFERENCES districts (district_code),
    CONSTRAINT fk_shelters_profile_image_seq FOREIGN KEY (profile_image_seq) REFERENCES images (image_seq),
    CONSTRAINT fk_shelters_background_image_seq FOREIGN KEY (background_image_seq) REFERENCES images (image_seq),
    CONSTRAINT fk_shelters_reg_usr_seq FOREIGN KEY (reg_usr_seq) REFERENCES users (user_seq),
    CONSTRAINT fk_shelters_mod_usr_seq FOREIGN KEY (mod_usr_seq) REFERENCES users (user_seq)
);

-- 보호소↔SHELTER 계정 1:1(양쪽 UNIQUE)
CREATE TABLE shelter_members (
    shelter_member_seq INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shelter_seq        INTEGER     NOT NULL,
    user_seq           INTEGER     NOT NULL,
    reg_dttm           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_shelter_members_shelter_seq UNIQUE (shelter_seq),
    CONSTRAINT uq_shelter_members_user_seq UNIQUE (user_seq),
    CONSTRAINT fk_shelter_members_shelter_seq FOREIGN KEY (shelter_seq) REFERENCES shelters (shelter_seq),
    CONSTRAINT fk_shelter_members_user_seq FOREIGN KEY (user_seq) REFERENCES users (user_seq)
);

