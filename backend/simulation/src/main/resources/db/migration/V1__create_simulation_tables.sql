-- DB 명세 v19 35~41·43·44. simulation 스키마(접속 currentSchema=simulation), 쓰기는 simulation 서비스만
-- core 스키마를 가리키는 user_seq·breed_seq는 FK 없는 논리 참조(Q420·Q482). simulation 테이블끼리의 FK는 유지
-- 스탯 7종은 모두 높을수록 좋음(Q485). 튜닝 수치는 코드 설정값이며 DB에 없음

-- ===== 35. 세션 =====
CREATE TABLE simulation_sessions (
    session_seq           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_seq              INTEGER     NOT NULL,
    breed_seq             INTEGER     NOT NULL,
    animal_name           VARCHAR(6)  NOT NULL,
    species_type          VARCHAR(10) NOT NULL,
    personality           VARCHAR(20) NOT NULL,
    status                VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS',
    expected_cost         INTEGER     NOT NULL,
    balance               INTEGER     NOT NULL,
    started_dttm          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ends_dttm             TIMESTAMPTZ NOT NULL,
    ended_dttm            TIMESTAMPTZ,
    satiety               SMALLINT    NOT NULL,
    hydration             SMALLINT    NOT NULL,
    cleanliness           SMALLINT    NOT NULL,
    bond                  SMALLINT    NOT NULL,
    calmness              SMALLINT    NOT NULL,
    health                SMALLINT    NOT NULL,
    energy                SMALLINT    NOT NULL,
    stats_calculated_dttm TIMESTAMPTZ NOT NULL,
    last_action_dttm      TIMESTAMPTZ,
    reg_dttm              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm              TIMESTAMPTZ,
    CONSTRAINT ck_sim_session_status CHECK (status IN ('IN_PROGRESS', 'COMPLETED', 'ABANDONED', 'FAILED')),
    CONSTRAINT ck_sim_session_species CHECK (species_type IN ('DOG', 'CAT')),
    CONSTRAINT ck_sim_session_personality CHECK (personality IN ('ACTIVE', 'TIMID', 'AGGRESSIVE', 'FRIENDLY')),
    -- balance는 음수 허용(M5)
    CONSTRAINT ck_sim_session_period CHECK (expected_cost >= 0 AND ends_dttm > started_dttm),
    CONSTRAINT ck_sim_session_ended CHECK (
        (status = 'IN_PROGRESS' AND ended_dttm IS NULL) OR (status <> 'IN_PROGRESS' AND ended_dttm IS NOT NULL)
    ),
    CONSTRAINT ck_sim_session_stats CHECK (
        satiety BETWEEN 0 AND 100 AND hydration BETWEEN 0 AND 100 AND cleanliness BETWEEN 0 AND 100
        AND bond BETWEEN 0 AND 100 AND calmness BETWEEN 0 AND 100 AND health BETWEEN 0 AND 100
        AND energy BETWEEN 0 AND 100
    )
);
-- M6: USER당 진행 중 세션 1건
CREATE UNIQUE INDEX uq_sim_session_user_active ON simulation_sessions (user_seq) WHERE status = 'IN_PROGRESS';
CREATE INDEX ix_sim_session_user ON simulation_sessions (user_seq, reg_dttm DESC);

-- ===== 36·37. 펫샵 물품(시드)·인벤토리 =====
CREATE TABLE simulation_shop_items (
    item_seq      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name     VARCHAR(100) NOT NULL,
    category      VARCHAR(20)  NOT NULL,
    is_consumable BOOLEAN      NOT NULL,
    price         INTEGER      NOT NULL,
    description   TEXT,
    image_key     VARCHAR(512),
    species_scope VARCHAR(10)  NOT NULL DEFAULT 'ALL',
    effects_jsonb JSONB,
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    display_order INTEGER      NOT NULL DEFAULT 0,
    reg_dttm      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm      TIMESTAMPTZ,
    CONSTRAINT ck_sim_item_category CHECK (category IN (
        'FOOD_BOWL', 'WATER_BOWL', 'LITTER_BOX', 'FOOD', 'SNACK', 'TOY', 'LITTER', 'SHAMPOO', 'MEDICINE'
    )),
    -- M9: 기구 4종만 비소모
    CONSTRAINT ck_sim_item_consumable CHECK ((category IN ('FOOD_BOWL', 'WATER_BOWL', 'LITTER_BOX', 'TOY')) = (is_consumable = FALSE)),
    CONSTRAINT ck_sim_item_scope CHECK (species_scope IN ('DOG', 'CAT', 'ALL') AND price >= 0)
);

CREATE TABLE simulation_inventory_items (
    inventory_item_seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_seq        BIGINT      NOT NULL,
    item_seq           BIGINT      NOT NULL,
    quantity           INTEGER     NOT NULL,
    reg_dttm           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm           TIMESTAMPTZ,
    CONSTRAINT uq_sim_inventory_session_item UNIQUE (session_seq, item_seq),
    CONSTRAINT ck_sim_inventory_qty CHECK (quantity >= 0),
    CONSTRAINT fk_sim_inventory_session FOREIGN KEY (session_seq) REFERENCES simulation_sessions (session_seq),
    CONSTRAINT fk_sim_inventory_item FOREIGN KEY (item_seq) REFERENCES simulation_shop_items (item_seq)
);

-- ===== 40. 산책 =====
CREATE TABLE simulation_walks (
    walk_seq            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_seq         BIGINT      NOT NULL,
    status              VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS',
    started_dttm        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_heartbeat_dttm TIMESTAMPTZ,
    ended_dttm          TIMESTAMPTZ,
    reg_dttm            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_sim_walk_status CHECK (
        (status = 'IN_PROGRESS' AND ended_dttm IS NULL) OR (status = 'ENDED' AND ended_dttm IS NOT NULL)
    ),
    CONSTRAINT fk_sim_walk_session FOREIGN KEY (session_seq) REFERENCES simulation_sessions (session_seq)
);
CREATE UNIQUE INDEX uq_sim_walk_session_active ON simulation_walks (session_seq) WHERE status = 'IN_PROGRESS';

-- ===== 41. 이벤트 시나리오(시드). 정답 행동 1개(Q486) =====
CREATE TABLE simulation_event_scenarios (
    scenario_seq            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                   VARCHAR(100) NOT NULL,
    description             TEXT         NOT NULL,
    trigger_context         VARCHAR(10)  NOT NULL,
    trigger_type            VARCHAR(20)  NOT NULL,
    trigger_condition_jsonb JSONB,
    cooldown_hours          SMALLINT,
    trigger_probability     NUMERIC(3, 2) NOT NULL DEFAULT 1.00,
    species_scope           VARCHAR(10)  NOT NULL DEFAULT 'ALL',
    personality_scope       VARCHAR(20),
    weight                  SMALLINT     NOT NULL DEFAULT 1,
    resolve_action_code     VARCHAR(30)  NOT NULL,
    resolve_cost            INTEGER      NOT NULL DEFAULT 0,
    resolve_effects_jsonb   JSONB,
    result_text             TEXT,
    neglect_effects_jsonb   JSONB,
    neglect_text            TEXT,
    is_active               BOOLEAN      NOT NULL DEFAULT TRUE,
    reg_dttm                TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm                TIMESTAMPTZ,
    CONSTRAINT ck_sim_scenario_trigger CHECK (
        trigger_context IN ('HOME', 'WALK') AND trigger_type IN ('RANDOM', 'CONDITION')
        AND (trigger_type <> 'CONDITION' OR trigger_condition_jsonb IS NOT NULL)
    ),
    CONSTRAINT ck_sim_scenario_scope CHECK (
        species_scope IN ('DOG', 'CAT', 'ALL')
        AND (personality_scope IS NULL OR personality_scope IN ('ACTIVE', 'TIMID', 'AGGRESSIVE', 'FRIENDLY'))
        AND weight > 0 AND (cooldown_hours IS NULL OR cooldown_hours > 0)
    ),
    -- Q481: CONDITION 판정 1회당 발생 확률. RANDOM은 1.00
    CONSTRAINT ck_sim_scenario_probability CHECK (trigger_probability > 0 AND trigger_probability <= 1),
    CONSTRAINT ck_sim_scenario_resolve CHECK (
        (trigger_context = 'HOME' AND resolve_action_code IN
            ('FEED', 'WATER', 'CLEAN_LITTER', 'BATHE', 'PLAY', 'SNACK', 'MEDICINE', 'VET_VISIT'))
        OR (trigger_context = 'WALK' AND resolve_action_code IN ('GIVE_WATER', 'GIVE_SNACK'))
    ),
    -- 해결 비용은 병원(VET_VISIT)만
    CONSTRAINT ck_sim_scenario_cost CHECK (resolve_cost >= 0 AND (resolve_action_code = 'VET_VISIT' OR resolve_cost = 0))
);

-- ===== 43·39. 발생 이벤트 ↔ 행동 로그(양쪽 NULL 허용 상호 FK: 로그 INSERT → occurrence UPDATE 순서) =====
CREATE TABLE simulation_event_occurrences (
    occurrence_seq          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_seq             BIGINT      NOT NULL,
    scenario_seq            BIGINT      NOT NULL,
    walk_seq                BIGINT,
    status                  VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    occurred_dttm           TIMESTAMPTZ NOT NULL,
    expires_dttm            TIMESTAMPTZ NOT NULL,
    resolved_dttm           TIMESTAMPTZ,
    resolved_action_log_seq BIGINT,
    reg_dttm                TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_sim_occurrence_status CHECK (
        (status = 'RESOLVED' AND resolved_dttm IS NOT NULL AND resolved_action_log_seq IS NOT NULL)
        OR (status IN ('PENDING', 'EXPIRED') AND resolved_dttm IS NULL AND resolved_action_log_seq IS NULL)
    ),
    CONSTRAINT fk_sim_occurrence_session FOREIGN KEY (session_seq) REFERENCES simulation_sessions (session_seq),
    CONSTRAINT fk_sim_occurrence_scenario FOREIGN KEY (scenario_seq) REFERENCES simulation_event_scenarios (scenario_seq),
    CONSTRAINT fk_sim_occurrence_walk FOREIGN KEY (walk_seq) REFERENCES simulation_walks (walk_seq)
);
-- M11: 세션당 미해결 이벤트 1건
CREATE UNIQUE INDEX uq_sim_occurrence_session_pending ON simulation_event_occurrences (session_seq) WHERE status = 'PENDING';
-- 쿨다운 판정(같은 시나리오 마지막 발생)
CREATE INDEX ix_sim_occurrence_scenario ON simulation_event_occurrences (session_seq, scenario_seq, occurred_dttm DESC);

CREATE TABLE simulation_action_logs (
    action_log_seq    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_seq       BIGINT      NOT NULL,
    action_type       VARCHAR(20) NOT NULL,
    action_code       VARCHAR(30) NOT NULL,
    item_seq          BIGINT,
    walk_seq          BIGINT,
    occurrence_seq    BIGINT,
    stat_delta_jsonb  JSONB,
    stats_after_jsonb JSONB       NOT NULL,
    reg_dttm          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_sim_action_type CHECK (action_type IN ('CARE', 'WALK', 'EVENT', 'SYSTEM')),
    CONSTRAINT fk_sim_action_session FOREIGN KEY (session_seq) REFERENCES simulation_sessions (session_seq),
    CONSTRAINT fk_sim_action_item FOREIGN KEY (item_seq) REFERENCES simulation_shop_items (item_seq),
    CONSTRAINT fk_sim_action_walk FOREIGN KEY (walk_seq) REFERENCES simulation_walks (walk_seq),
    CONSTRAINT fk_sim_action_occurrence FOREIGN KEY (occurrence_seq) REFERENCES simulation_event_occurrences (occurrence_seq)
);
CREATE INDEX ix_sim_action_session ON simulation_action_logs (session_seq, reg_dttm DESC);

ALTER TABLE simulation_event_occurrences ADD CONSTRAINT fk_sim_occurrence_resolved_log
    FOREIGN KEY (resolved_action_log_seq) REFERENCES simulation_action_logs (action_log_seq);

-- ===== 38. 지출 내역 =====
CREATE TABLE simulation_transactions (
    transaction_seq  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_seq      BIGINT       NOT NULL,
    transaction_type VARCHAR(20)  NOT NULL,
    item_seq         BIGINT,
    occurrence_seq   BIGINT,
    quantity         INTEGER      NOT NULL DEFAULT 1,
    amount           INTEGER      NOT NULL,
    balance_after    INTEGER      NOT NULL,
    description      VARCHAR(200),
    reg_dttm         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- M15: PURCHASE는 물품, EVENT(병원 진료비)는 발생 이벤트 필수
    CONSTRAINT ck_sim_transaction_type CHECK (
        (transaction_type = 'PURCHASE' AND item_seq IS NOT NULL)
        OR (transaction_type = 'EVENT' AND occurrence_seq IS NOT NULL)
    ),
    CONSTRAINT ck_sim_transaction_amount CHECK (quantity >= 1 AND amount >= 0),
    CONSTRAINT fk_sim_transaction_session FOREIGN KEY (session_seq) REFERENCES simulation_sessions (session_seq),
    CONSTRAINT fk_sim_transaction_item FOREIGN KEY (item_seq) REFERENCES simulation_shop_items (item_seq),
    CONSTRAINT fk_sim_transaction_occurrence FOREIGN KEY (occurrence_seq) REFERENCES simulation_event_occurrences (occurrence_seq)
);
CREATE INDEX ix_sim_transaction_session ON simulation_transactions (session_seq, reg_dttm DESC);

-- ===== 44. 종료 리포트(세션 1:1, 영구 보존) =====
CREATE TABLE simulation_reports (
    report_seq              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_seq             BIGINT      NOT NULL,
    expected_cost           INTEGER     NOT NULL,
    total_spent             INTEGER     NOT NULL,
    spent_by_category_jsonb JSONB       NOT NULL,
    daily_spent_jsonb       JSONB       NOT NULL,
    final_stats_jsonb       JSONB       NOT NULL,
    action_count            INTEGER     NOT NULL,
    event_count             INTEGER     NOT NULL,
    event_resolved_count    INTEGER     NOT NULL DEFAULT 0,
    walk_count              INTEGER     NOT NULL,
    summary                 TEXT,
    reg_dttm                TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_sim_report_session UNIQUE (session_seq),
    CONSTRAINT fk_sim_report_session FOREIGN KEY (session_seq) REFERENCES simulation_sessions (session_seq)
);
-- Q487: summary 고아 복구 스케줄러 조회
CREATE INDEX ix_sim_report_summary_null ON simulation_reports (reg_dttm) WHERE summary IS NULL;
